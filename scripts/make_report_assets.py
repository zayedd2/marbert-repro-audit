#!/usr/bin/env python
"""Rebuild EVERY table, figure and report number from the saved run outputs. No GPU needed.

  python scripts/make_report_assets.py
  python scripts/make_report_assets.py --results-root results_synthetic --data-root data_synthetic

Writes
  <results-root>/tables/*.csv|.md|.tex   result tables (CSV = full precision, TeX = report-ready)
  <results-root>/figures/*.pdf|.png      figures
  <results-root>/SUMMARY.md              Markdown overview (shown on GitHub)
  <report-dir>/numbers.tex, tab_*.tex, fig_*.pdf   what report/experiments_results.tex reads
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

import _bootstrap  # noqa: F401
import pandas as pd

from marbert_audit import errors, figures, latex, summary
from marbert_audit.config import REPO_ROOT, load_config
from marbert_audit.selection import collect_runs, expected_runs
from marbert_audit.train import is_done, run_dir_for


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-root", default=str(REPO_ROOT / "results"))
    ap.add_argument("--data-root", default=str(REPO_ROOT / "data"))
    ap.add_argument("--report-dir", default=None, help="default: report/generated (or <results-root>/generated for non-default roots)")
    ap.add_argument("--skip-bootstrap", action="store_true", help="faster; margins table without CIs")
    args = ap.parse_args()

    cfg = load_config()
    if args.skip_bootstrap:
        cfg["bootstrap"]["n_resamples"] = 200
    res = Path(args.results_root)
    default_root = res.resolve() == (REPO_ROOT / "results").resolve()
    report_dir = Path(args.report_dir) if args.report_dir else (REPO_ROOT / "report" / "generated" if default_root else res / "generated")
    tables, figs = res / "tables", res / "figures"
    for p in (tables, figs, report_dir):
        p.mkdir(parents=True, exist_ok=True)

    exp = expected_runs(cfg)
    missing = [r for r in exp if not is_done(run_dir_for(res, *r))]
    runs = collect_runs(res, cfg)
    print(f"{len(runs)} completed runs found, {len(missing)} of {len(exp)} expected runs missing.")
    for r in missing:
        print("  missing:", "/".join(map(str, r)))
    if runs.empty:
        print("Nothing to summarise yet.")
        return
    synthetic = bool((runs["backend"] == "dummy").any())
    if synthetic and default_root:
        raise SystemExit("Synthetic runs found inside results/ - remove them; they must never mix with real results.")

    # ---------------------------------------------------------------- tables
    repro = summary.reproduction_table(runs, cfg)
    indep = summary.independent_table(runs, cfg, "independent")
    hist_tbl = summary.independent_table(runs, cfg, "historical")
    ckpt = summary.checkpoint_table(runs, cfg)
    print("bootstrapping margins ...")
    margins = summary.margins_table(runs, cfg, res)
    per_cls = summary.per_class_table(runs, cfg)
    cms = errors.confusion_matrices(runs, cfg)
    subgroups = errors.subgroup_table(runs, cfg, args.data_root)

    runs.to_csv(tables / "all_runs.csv", index=False)
    for name, df in {"reproduction": repro, "independent": indep, "historical_all_metrics": hist_tbl,
                     "checkpoint_diagnostic": ckpt, "margins": margins, "per_class": per_cls,
                     "subgroups": subgroups, "confusion_matrices": errors.confusion_long(cms, cfg)}.items():
        df.to_csv(tables / f"{name}.csv", index=False)

    tex = {
        "tab_reproduction": latex.tex_reproduction(repro, cfg),
        "tab_independent": latex.tex_independent(indep, cfg),
        "tab_checkpoint": latex.tex_checkpoint(ckpt, cfg),
        "tab_margins": latex.tex_margins(margins, cfg),
        "tab_per_class": latex.tex_per_class(per_cls, cfg),
        "tab_subgroups": latex.tex_subgroups(subgroups, cfg),
    }
    numbers = latex.numbers_tex(runs, repro, indep, hist_tbl, ckpt, margins, cfg, len(exp), synthetic)
    for name, body in {**tex, "numbers": numbers}.items():
        header = "% AUTO-GENERATED by scripts/make_report_assets.py - edit the code, not this file.\n"
        (tables / f"{name}.tex").write_text(header + body, encoding="utf-8")
        (report_dir / f"{name}.tex").write_text(header + body, encoding="utf-8")
    audit_tex = tables / "tab_data_audit.tex"
    if audit_tex.exists():
        shutil.copy(audit_tex, report_dir / "tab_data_audit.tex")

    fail = errors.failure_examples(runs, cfg, args.data_root)
    if not fail.empty:
        (res / "analysis").mkdir(exist_ok=True)
        fail.to_csv(res / "analysis" / "failure_examples.csv", index=False)  # contains tweet text; git-ignored

    # ---------------------------------------------------------------- figures
    figures.fig_reproduction(repro, runs, cfg, figs, synthetic)
    figures.fig_learning_curves(runs, cfg, figs, synthetic)
    figures.fig_checkpoint_gap(runs, cfg, figs, synthetic)
    figures.fig_margins(margins, cfg, figs, synthetic)
    figures.fig_confusions(cms, cfg, figs, synthetic)
    for pdf in figs.glob("*.pdf"):
        shutil.copy(pdf, report_dir / pdf.name)

    # ---------------------------------------------------------------- markdown summary
    md = ["# Results summary", ""]
    if synthetic:
        md += ["> **SYNTHETIC DRY RUN - NOT REAL RESULTS.** Produced by the dummy back-end to test the pipeline.", ""]
    md += [f"Completed runs: **{len(runs)} / {len(exp)}**." + (f" Missing: {len(missing)}." if missing else ""), "",
           "## RQ1 - Reproduction (historical protocol: best epoch on test)", "",
           latex.markdown(repro, {"dataset_name": "Dataset", "metric": "Metric", "model_name": "Model", "published": "Published",
                                  "mean": "Ours mean", "sd": "SD", "gap": "Gap (pp)", "ranking_holds": "Ranking holds", "verdict": "Verdict"}),
           "## Main result (independent protocol: checkpoint chosen on dev macro-F1)", "",
           latex.markdown(indep, {"dataset_name": "Dataset", "model_name": "Model", "hist_metric": "Hist. metric", "hist_mean": "Mean",
                                  "hist_sd": "SD", "macro_f1_mean": "Macro-F1", "macro_f1_sd": "SD", "selected_epochs": "Dev-selected epochs"}),
           "## RQ2 - Checkpoint diagnostic (independent runs)", "",
           latex.markdown(ckpt, {"dataset_name": "Dataset", "model_name": "Model", "metric": "Metric", "selected_mean": "Dev-selected",
                                 "max_mean": "Best-on-test", "gap_mean": "Gap mean", "gap_max": "Gap max"}),
           "## RQ3/RQ4 - MARBERT minus AraBERT", "",
           latex.markdown(margins, {"protocol": "Protocol", "dataset_name": "Dataset", "metric": "Metric", "diff_mean": "Δ mean",
                                    "diff_sd": "Δ SD (seeds)", "ci_low": "CI low", "ci_high": "CI high", "marbert_wins": "MARBERT wins",
                                    "ranking_changes_with_metric": "Ranking changes with metric"}),
           "## Figures", ""]
    for name in ("fig_reproduction", "fig_learning_curves", "fig_checkpoint_gap", "fig_margins", "fig_confusion_matrices"):
        if (figs / f"{name}.png").exists():
            md.append(f"![{name}](figures/{name}.png)\n")
    (res / "SUMMARY.md").write_text("\n".join(md), encoding="utf-8")
    (res / "assets_status.json").write_text(json.dumps({"runs_done": len(runs), "runs_expected": len(exp),
                                                         "missing": ["/".join(map(str, r)) for r in missing],
                                                         "synthetic": synthetic}, indent=2) + "\n", encoding="utf-8")
    print(f"Tables  -> {tables}\nFigures -> {figs}\nReport  -> {report_dir}\nSummary -> {res / 'SUMMARY.md'}")


if __name__ == "__main__":
    pd.set_option("display.width", 160)
    main()
