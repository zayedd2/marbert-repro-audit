#!/usr/bin/env python
"""Data audit: counts, label distributions, duplicates, train/test and cross-dataset overlap.

  python scripts/data_audit.py
Writes results/tables/data_audit.csv, data_overlap.csv, data_source_overlap.csv, data_audit.json and tab_data_audit.tex.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import _bootstrap  # noqa: F401
import pandas as pd

from marbert_audit.audit import run_audit
from marbert_audit.config import REPO_ROOT, load_config
from marbert_audit.latex import tex_data_audit


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-root", default=str(REPO_ROOT / "data"))
    ap.add_argument("--results-root", default=str(REPO_ROOT / "results"))
    args = ap.parse_args()
    cfg = load_config()
    rows, overlap, manifest = run_audit(cfg, args.data_root)
    if rows.empty:
        raise SystemExit("No processed data found. Run scripts/prepare_data.py first.")
    out = Path(args.results_root) / "tables"
    out.mkdir(parents=True, exist_ok=True)
    rows.to_csv(out / "data_audit.csv", index=False)
    src = pd.DataFrame(manifest.pop("_source_overlap", []))
    if not src.empty:
        src.to_csv(out / "data_source_overlap.csv", index=False)
        print("\nOverlap between pooled sources (before pooling):")
        print(src.to_string(index=False))
    overlap.to_csv(out / "data_overlap.csv", index=False)
    (out / "data_audit.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "tab_data_audit.tex").write_text("% AUTO-GENERATED by scripts/data_audit.py\n" + tex_data_audit(rows), encoding="utf-8")
    print(rows.to_string(index=False))
    print("\nTest items whose text also appears in a training set:")
    print(overlap.to_string(index=False))
    for d, m in manifest.items():
        if any(m.get("size_differences", {}).values()):
            print(f"NOTE {d}: size differs from [1] Table A.1 by {m['size_differences']} - record in docs/DEPARTURES.md")


if __name__ == "__main__":
    main()
